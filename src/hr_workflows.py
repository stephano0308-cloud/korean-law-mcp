def list_workflows() -> Dict[str, object]:
    """제공 가능한 인사 업무 워크플로우 목록을 반환한다."""
    items = [
        {
            "workflow_id": key,
            "title": wf["title"],
            "category": wf["category"],
            "summary": wf["summary"],
            "step_count": len(wf["steps"]),
        }
        for key, wf in HR_WORKFLOWS.items()
    ]
    return {
        "disclaimer": DISCLAIMER,
        "count": len(items),
        "workflows": items,
    }


def get_workflow(workflow_id: str) -> Dict[str, object]:
    """특정 인사 업무의 시계열 체크리스트를 반환한다.

    workflow_id 또는 제목/분류 키워드로 조회할 수 있다.
    """
    key = (workflow_id or "").strip()
    wf = HR_WORKFLOWS.get(key)

    # ID 불일치 시 제목·분류 키워드로 탐색
    if wf is None:
        lowered = key.lower()
        for wf_id, candidate in HR_WORKFLOWS.items():
            haystack = f"{wf_id} {candidate['title']} {candidate['category']}".lower()
            if lowered and lowered in haystack:
                key, wf = wf_id, candidate
                break

    if wf is None:
        return {
            "error": f"'{workflow_id}'에 해당하는 워크플로우를 찾지 못했습니다.",
            "available": [
                {"workflow_id": k, "title": v["title"]} for k, v in HR_WORKFLOWS.items()
            ],
        }

    return {
        "workflow_id": key,
        "title": wf["title"],
        "category": wf["category"],
        "summary": wf["summary"],
        "disclaimer": DISCLAIMER,
        "steps": wf["steps"],
        "cautions": wf.get("cautions", []),
        "지방공무원_참고": wf.get("local_reference", ""),
        "verify_queries": wf.get("verify_queries", []),
        "usage_note": (
            "이 체크리스트를 답변에 사용할 때는 verify_queries의 검색어로 "
            "search_law_tool/search_admin_rule_tool을 호출해 최신 규정과 대조한 후, "
            "차이가 있으면 최신 원문을 우선하세요."
        ),
    }


