def suggest_keywords(issue_text: str) -> Dict[str, object]:
    """사안 문구를 바탕으로 우선 검색할 인사 키워드 후보를 추천한다."""
    text = (issue_text or "").strip()
    recommended: List[str] = []

    # 쟁점명 토큰이 사안 문구에 포함되면 해당 쟁점 키워드를 추천
    for issue, keywords in HR_ISSUE_KEYWORDS.items():
        issue_tokens = issue.replace("(참고)", "").replace("·", " ").split()
        if any(token and token in text for token in issue_tokens):
            recommended.extend(keywords)

    # 매칭 실패 시 핵심 법령 + 사안 문구 조합을 기본 추천
    if not recommended and text:
        head = text[:20]
        recommended = [
            f"국가공무원법 {head}",
            f"공무원임용령 {head}",
            f"국가공무원 복무규정 {head}",
            f"공무원보수규정 {head}",
            f"공무원 징계령 {head}",
        ]

    seen = set()
    unique: List[str] = []
    for item in recommended:
        if item not in seen:
            seen.add(item)
            unique.append(item)

    return {
        "issue_text": issue_text,
        "core_keywords": HR_CORE_KEYWORDS,
        "mpm_key_rules": MPM_KEY_RULES,
        "issue_keywords": HR_ISSUE_KEYWORDS,
        "recommended_queries": unique[:12],
        "note": (
            "추천 키워드는 검색 보조용입니다. 법령은 search_law_tool, "
            "인사혁신처 예규·지침은 search_admin_rule_tool 및 "
            "search_mpm_catalog_tool로 실제 원문을 확인해 검증하세요."
        ),
    }
